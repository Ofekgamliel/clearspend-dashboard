from __future__ import annotations

import unittest

from clearspend.database.postgresql_migrations import v001_observation_reviews


class Result:
    def __init__(self, rows):
        self.rows = list(rows)

    def fetchone(self):
        return self.rows[0]

    def fetchall(self):
        return self.rows


class SyntheticCatalogConnection:
    def __init__(self) -> None:
        self.missing_objects: set[str] = set()
        self.unexpected_table_grants: list[dict] = []
        self.unexpected_sequence_grants: list[dict] = []
        self.runtime_owned_tables: list[dict] = []
        self.executed: list[tuple[str, object]] = []

    def execute(self, sql, parameters=None):
        self.executed.append((sql, parameters))
        if parameters is None and sql.lstrip().startswith(("CREATE", "GRANT", "REVOKE")):
            return Result([])
        if "to_regclass" in sql:
            return Result([{"present": parameters[0] not in self.missing_objects}])
        if "information_schema.columns" in sql:
            table = parameters[0]
            return Result(
                [
                    {"column_name": column}
                    for column in v001_observation_reviews.TABLE_COLUMNS[table]
                ]
            )
        if "information_schema.table_privileges" in sql and "grantee='clearspend_app'" in sql:
            table = parameters[0]
            privileges = (
                {"SELECT"}
                if table == "schema_migrations"
                else {"SELECT", "INSERT", "UPDATE", "DELETE"}
            )
            return Result([{"privilege_type": value} for value in privileges])
        if "has_sequence_privilege" in sql:
            return Result([{"runtime_allowed": True}])
        if "information_schema.table_privileges" in sql:
            return Result(self.unexpected_table_grants)
        if "information_schema.usage_privileges" in sql:
            return Result(self.unexpected_sequence_grants)
        if "pg_catalog.pg_tables" in sql:
            return Result(self.runtime_owned_tables)
        raise AssertionError(f"Unexpected verification SQL: {sql}")


class PostgreSQLMigrationV001Tests(unittest.TestCase):
    def test_apply_creates_schema_slice_and_explicit_grants(self) -> None:
        connection = SyntheticCatalogConnection()

        v001_observation_reviews.apply(connection)

        statements = [sql for sql, _ in connection.executed]
        self.assertEqual(
            len(statements),
            len(v001_observation_reviews.CREATE_STATEMENTS)
            + len(v001_observation_reviews.PRIVILEGE_STATEMENTS),
        )
        combined = "\n".join(statements)
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", combined)
        self.assertIn("active BOOLEAN NOT NULL DEFAULT TRUE", combined)
        self.assertIn("GRANT SELECT, INSERT, UPDATE, DELETE", combined)
        self.assertIn("GRANT USAGE, SELECT ON SEQUENCE", combined)
        for denied_role in ("PUBLIC", "anon", "authenticated", "service_role"):
            self.assertIn(denied_role, combined)
        self.assertNotIn("ALTER DEFAULT PRIVILEGES", combined)

    def test_verify_accepts_complete_private_schema_slice(self) -> None:
        connection = SyntheticCatalogConnection()

        self.assertEqual(v001_observation_reviews.verify(connection), [])

    def test_verify_reports_missing_objects_and_api_access(self) -> None:
        connection = SyntheticCatalogConnection()
        connection.missing_objects = {
            "clearspend.transactions",
            "clearspend.idx_observation_reviews_active",
        }
        connection.unexpected_table_grants = [
            {"grantee": "anon", "table_name": "imports", "privilege_type": "SELECT"}
        ]
        connection.unexpected_sequence_grants = [
            {
                "grantee": "authenticated",
                "object_name": "imports_id_seq",
                "privilege_type": "USAGE",
            }
        ]
        connection.runtime_owned_tables = [{"tablename": "observation_reviews"}]

        problems = v001_observation_reviews.verify(connection)

        self.assertIn("Missing table: clearspend.transactions", problems)
        self.assertIn("Missing index: clearspend.idx_observation_reviews_active", problems)
        self.assertIn("API roles or PUBLIC can access ClearSpend tables", problems)
        self.assertIn("API roles or PUBLIC can access ClearSpend sequences", problems)
        self.assertIn("clearspend_app owns ClearSpend tables", problems)


if __name__ == "__main__":
    unittest.main()
