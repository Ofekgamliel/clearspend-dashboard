def apply(connection: Any) -> None:
    for statement in CREATE_STATEMENTS + PRIVILEGE_STATEMENTS:
        connection.execute(statement)


def _privileges(connection: Any, object_name: str) -> set[str]:
    return {
        row["privilege_type"]
        for row in connection.execute(
            """SELECT privilege_type FROM information_schema.table_privileges
            WHERE table_schema='clearspend' AND table_name=?
            AND grantee='clearspend_app'""",
            (object_name,),
        ).fetchall()
    }


def verify(connection: Any) -> list[str]:
    problems: list[str] = []
    for table, expected_columns in TABLE_COLUMNS.items():
        table_row = connection.execute(
            "SELECT to_regclass(?) IS NOT NULL AS present",
            (f"clearspend.{table}",),
        ).fetchone()
        if not table_row["present"]:
            problems.append(f"Missing table: clearspend.{table}")
            continue
        rows = connection.execute(
            """SELECT column_name FROM information_schema.columns
            WHERE table_schema='clearspend' AND table_name=?""",
            (table,),
        ).fetchall()
        actual_columns = {row["column_name"] for row in rows}
        for column in sorted(expected_columns - actual_columns):
            problems.append(f"Missing column: clearspend.{table}.{column}")
        expected_privileges = {"SELECT", "INSERT", "UPDATE", "DELETE"}
        if _privileges(connection, table) != expected_privileges:
            problems.append(f"Incorrect clearspend_app privileges: clearspend.{table}")

    for index in sorted(INDEXES):
        row = connection.execute(
            "SELECT to_regclass(?) IS NOT NULL AS present",
            (f"clearspend.{index}",),
        ).fetchone()
        if not row["present"]:
            problems.append(f"Missing index: clearspend.{index}")

    migration_privileges = _privileges(connection, "schema_migrations")
    if migration_privileges != {"SELECT"}:
        problems.append("Incorrect clearspend_app privileges: clearspend.schema_migrations")

    for sequence in sorted(IDENTITY_SEQUENCES):
        row = connection.execute(
            """SELECT has_sequence_privilege(
            'clearspend_app', ?, 'USAGE,SELECT') AS runtime_allowed""",
            (f"clearspend.{sequence}",),
        ).fetchone()
        if not row["runtime_allowed"]:
            problems.append(f"Missing clearspend_app sequence privileges: {sequence}")

    unexpected_rows = connection.execute(
        """SELECT grantee,table_name,privilege_type
        FROM information_schema.table_privileges
        WHERE table_schema='clearspend'
        AND grantee IN ('PUBLIC','anon','authenticated','service_role')"""
    ).fetchall()
    if unexpected_rows:
        problems.append("API roles or PUBLIC can access ClearSpend tables")

    unexpected_sequence_rows = connection.execute(
        """SELECT grantee,object_name,privilege_type
        FROM information_schema.usage_privileges
        WHERE object_schema='clearspend'
        AND object_type='SEQUENCE'
        AND grantee IN ('PUBLIC','anon','authenticated','service_role')"""
    ).fetchall()
    if unexpected_sequence_rows:
        problems.append("API roles or PUBLIC can access ClearSpend sequences")

    owner_rows = connection.execute(
        """SELECT tablename FROM pg_catalog.pg_tables
        WHERE schemaname='clearspend' AND tableowner='clearspend_app'"""
    ).fetchall()
    if owner_rows:
        problems.append("clearspend_app owns ClearSpend tables")
    return problems
